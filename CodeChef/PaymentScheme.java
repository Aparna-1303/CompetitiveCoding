import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
		Scanner sc = new Scanner(System.in);
		int c = sc.nextInt();
		int min = 100 + c * 4;
		int max = 300;
		if(min < max)
		{
		    System.out.println(min);
		}
		else
		{
		    System.out.println(max);
		}

	}
}
